import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import {createApp} from '../server.js';
test('local corrections persist safely, reject foreign/stale writes, and do not add editing to the public artifact',async t=>{
 const directory=mkdtempSync(join(tmpdir(),'seahawk-editor-'));t.after(()=>rmSync(directory,{recursive:true,force:true}));
 const correctionsFile=join(directory,'corrections.json');writeFileSync(correctionsFile,'{}');writeFileSync(join(directory,'index.html'),readFileSync('dist/index.html'));
 const app=createApp({directory,correctionsFile,editing:true});app.listen(0,'127.0.0.1');await once(app,'listening');t.after(()=>new Promise(done=>app.close(done)));
 const origin=`http://127.0.0.1:${app.address().port}`;
 const input={id:'E003',text:'Corrected family name.\n\n<script>unsafe</script>',note:'Dad remembers <this> trip.',revision:null};
 const save=(data,from=origin)=>fetch(origin+'/__local/entries',{method:'POST',headers:{Origin:from,'Content-Type':'application/json'},body:JSON.stringify(data)});
 assert.equal((await save(input,'https://example.com')).status,403);
 assert.equal((await save({...input,id:'unknown'})).status,400);
 const response=await save(input);assert.equal(response.status,200);const saved=await response.json();assert(saved.updated_at);
 assert.equal(JSON.parse(readFileSync(correctionsFile)).E003.text,input.text);
 const rendered=readFileSync(join(directory,'index.html'),'utf8');assert(rendered.includes('&lt;script&gt;unsafe&lt;/script&gt;'));assert(rendered.includes('Dad remembers &lt;this&gt; trip.'));assert(!rendered.includes('<script>unsafe'));
 assert.equal((await save(input)).status,409);
 assert.equal((await save({...input,revision:saved.updated_at,note:'Updated note'})).status,200);
 const continuation={id:'P-page-029-prefix',text:'Corrected continuation only.',note:'A separate family clarification.',revision:null};
 assert.equal((await save(continuation)).status,200);
 // July 25 spans pages 33–34, both of which now also contain artifacts.
 for(const id of ['E-ed2b609889','E-1bc054bfa7']){
  const july={id,text:'July 25 correction for '+id,note:'Clarified by Dad.',revision:null};
  const first=await save(july);assert.equal(first.status,200);const revision=await first.json();
  assert.equal((await save({...july,text:july.text+' Updated.',revision:revision.updated_at})).status,200);
 }
 const before=JSON.parse(readFileSync(correctionsFile));
 const dateInput={id:'E-1bc054bfa7',text:before['E-1bc054bfa7'].text,note:'Continuation note',revision:before['E-1bc054bfa7'].updated_at,date_override:{date:'1997-07-26',end_date:null},date_revision:null};
 const dateResponse=await save(dateInput);assert.equal(dateResponse.status,200);const dated=await dateResponse.json();
 assert.match(readFileSync(join(directory,'index.html'),'utf8'),/data-entry-title="July 26, 1997"/);
 const parent=before['E-ed2b609889'];
 assert.equal((await save({id:'E-ed2b609889',text:parent.text,note:parent.note,revision:parent.updated_at,date_override:{date:'1997-07-27',end_date:null},date_revision:null})).status,409);
 assert.equal((await save({...dateInput,revision:dated.updated_at,date_revision:dated.date_updated_at,date_override:{date:'1997-02-30',end_date:null}})).status,400);
 assert.equal((await save({id:dateInput.id,text:dated.text,note:'Note-only update',revision:dated.updated_at})).status,200);
 assert.deepEqual(JSON.parse(readFileSync(correctionsFile))[dateInput.id].date_override,dateInput.date_override);
 const persisted=JSON.parse(readFileSync(correctionsFile));assert.equal(persisted.E003.text,input.text);assert.equal(persisted['P-page-029-prefix'].text,continuation.text);
 const complete=readFileSync(join(directory,'index.html'),'utf8').match(/<article[^>]*>[\s\S]*?<\/article>/g).find(article=>article.includes('id="context-P-page-029-prefix"'));assert(complete.includes(continuation.text));assert(complete.includes(continuation.note));
 assert.equal((await save(continuation)).status,409);
 assert.match(await(await fetch(origin)).text(),/\/__local\/editor.js/);
 const editorScript=await fetch(origin+'/__local/editor.js');
 assert.equal(editorScript.status,200);
 assert.match(await editorScript.text(),/Edit journal entry/);
 assert.doesNotMatch(readFileSync('dist/index.html','utf8'),/__local|edit-entry|entry-editor/);
 const publicApp=createApp();publicApp.listen(0,'127.0.0.1');await once(publicApp,'listening');t.after(()=>new Promise(done=>publicApp.close(done)));
 const publicOrigin=`http://127.0.0.1:${publicApp.address().port}`;
 assert.equal((await fetch(publicOrigin+'/__local/editor.js')).status,404);assert.equal((await fetch(publicOrigin+'/__local/entries',{method:'POST'})).status,405);
});
